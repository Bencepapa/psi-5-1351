; Psi-5 EasyFlash: mouse support, ROM part (own bank, ROML at $8000, called via mouse_ram.asm).
; Only touches I/O, RAM below $8000 and the RAM part's variables.
; Pointer: sprite 7 in the text rows, multiplexed by the RAM part (the ships use it above the
; split). Mouse in port 2.
; - click a word on the menu row (row 14): its shortcut key goes into the game's key queue
; - while the game asks for an item or a position: click a list row = that letter or row number
; - otherwise, on the list screens:
;   Engineering status: click a device = enable/cancel it ($95AC)
;   Navigation, status or course list: click a course = select it (rank 1, $8AE7)
;   Scanning status: click a target = examine it ($8CFC)
;   Repair status: click a damaged item = types Assign + its letter, the game asks how many
;   Priority lists (Engineering, Weapons, Repair, Scanning): drag a row to another row = rank ($8AE7)
; - outside menus a click is the fire button
KQUEUE   = $03CA
KCOUNT   = $4E
DEVSTATE = $58CC
TITLE    = $5000+15*40
MENU     = $5000+14*40
LIST0    = 17            ; first list row
DRAGR    = $DFFA         ; greyed row while dragging, 0 = none (end of the cartridge's RAM)
BASEC    = $DFFB         ; the list rows' colour
FLT      = $DFFC         ; flash: frames left, $FF = start it
FLLO     = $DFFD         ; rows FLLO-FLHI changed, FLTGT is the moved one
FLHI     = $DFFE
FLTGT    = $DFFF
COLGREY  = 12
COLHOVER = 1              ; white
COLLABEL = 3              ; cyan, for non-interactive prompt/suffix text
HOVC     = $DBE8          ; colour RAM past the screen: holds a colour
HOVD1    = $53F6          ; unused end of the text screen: scratch
HOVD2    = $53F7
COLMOVED = 7             ; yellow
COLSHIFT = 6             ; blue
FLASHLEN = 40            ; frames
; The arrow's sprite block: $6080 (block $82), a piece of the frame's art in the top row of the
; bitmap. Nothing in the VIC bank is free, so this block shows the arrow from line $82 down and
; gets its art back at line $2D. SHPUT and SHRST are generated by efbuild.py, which reads the art
; and the shape below (unrolled LDA #/STA abs: 6 cycles a byte). SHSIGA/SHSIG: an art byte that
; says the game's bitmap is loaded.

        * = $8000
        JMP MPRE        ; fixed entry points for the RAM part
        JMP MJOY
        JMP MKEY
        JMP MSPR
        JMP MTOP
        JMP MXOR
        JMP MLOAD
; ---- IRQ: pots, pointer ----
MPRE:   LDA $D419
        AND $D41A
        EOR #$FF        ; $FF on both pots = no 1351 in port 2
        STA MOUSEON
        BNE MP0
        RTS
MP0:    LDA $D419
        LDY OLDX
        JSR MOVCHK
        STY OLDX
        CMP #$80        ; /2 keeping the sign: x in 2-pixel units 0-159
        ROR A
        CLC
        ADC XP
        CMP #160
        BCC MP2
        CMP #$C8        ; past the right edge (160-199) or the left edge (wrapped)
        LDA #159
        BCC MP2
        LDA #0
MP2:    STA XP
        LSR A
        LSR A
        STA CCOL
        LDA $D41A
        LDY OLDY
        JSR MOVCHK
        STY OLDY
        EOR #$FF        ; pot Y grows upwards
        SEC
        ADC YP
        CMP #110        ; not above the split (the sprite is set at raster $9A-$9E)
        BCS MP5
        LDA #110
MP5:    CMP #200
        BCC MP6
        LDA #199
MP6:    STA YP
        TAX
        LSR A
        LSR A
        LSR A
        STA CROW
        TXA
        CLC
        ADC #50
        STA SPY
        LDA #0          ; sprite X = 2*XP+24
        STA SPM
        LDA XP
        ASL A
        ROR SPM
        ADC #24
        STA SPX
        BCC MP7
        LDA #$80
        STA SPM
MP7:
MP9:    ; falls through to VIS
; ---- list colours: the dragged row grey, then a flash of the rows that changed ----
VIS:    JSR LABELS       ; labels stay light blue during hover, press and release
        LDA CANCEL
        BEQ VGO
        JMP VCANCEL
VGO:    LDA BTN
        BNE VHOLD
        JMP VREL
VHOLD:  JSR HVCLR
        LDA DRAGR
        BNE VPRE
        LDX PROW
        CPX #LIST0
        BCS VV0
        JMP VFL
VV0:
        JSR RANKABLE
        BEQ VRANK
        JMP VFL
VRANK:
        JSR ITEM
        BNE VITEM
        JMP VFL
VITEM:
        LDX PROW
        STX DRAGR
        JSR COLRD
        STA BASEC
        LDA #COLGREY
        LDX PROW
        JSR PAINT
; the row under the pointer previews the new position (the last item's row past the list's end).
; ITEM uses TMP2/TMP3, ROWADR uses MNEW; MOLD is free here (MOVCHK has finished).
VPRE:   LDA #0
        STA MOLD
        LDX CROW
        CPX #LIST0
        BCC VP3
        STX MOLD
        LDA PROW
        PHA
VP1:    LDA MOLD
        STA PROW
        JSR ITEM
        BNE VP2
        DEC MOLD
        LDA MOLD
        CMP #LIST0
        BCS VP1
        LDA #0
        STA MOLD
VP2:    PLA
        STA PROW
VP3:    LDA MOLD
        CMP DRAGR
        BNE VP4
        LDA #0
        STA MOLD
VP4:    LDA MOLD
        CMP PREVW
        BEQ VP9         ; repaint only on a change
        LDX PREVW
        BEQ VP5
        LDA BASEC
        JSR PAINT
VP5:    LDX MOLD
        STX PREVW
        BEQ VP9
        LDA #COLMOVED
        JSR PAINT
VP9:    JMP VFL
VREL:   LDX DRAGR
        BEQ VFL
        LDX PREVW
        BEQ VR1
        LDA BASEC
        JSR PAINT
        LDA #0
        STA PREVW
VR1:    LDX DRAGR
        LDA BASEC
        JSR PAINT
        LDA #0
        STA DRAGR
        RTS
VCANCEL:LDA #0
        STA BTN
        JMP VREL
VFL:    LDA FLT
        BNE VFL1
        JMP HOVER
VFL1:
        CMP #$FF
        BNE VF3
        LDX FLLO
VF1:    LDA #COLSHIFT
        CPX FLTGT
        BNE VF2
        LDA #COLMOVED
VF2:    JSR PAINT
        INX
        CPX FLHI
        BCC VF1
        BEQ VF1
        LDA #FLASHLEN
        STA FLT
VX:     RTS
VF3:    DEC FLT
        BNE VX
        LDX FLLO
VF4:    LDA BASEC
        JSR PAINT
        INX
        CPX FLHI
        BCC VF4
        BEQ VF4
        RTS
; ---- hover: what a click would act on turns white, as the game's own highlights ----
; HOVR/HOVS/HOVE: the painted row (0 = none) and its columns; its colour is kept in an unused
; colour RAM cell. MOLD, HOVD1, HOVD2: the wanted row and columns, only used in here.
HOVER:  LDA BTN
        ORA DRAGR
        BEQ HV0
        RTS
HV0:
        STA MOLD
        LDA MENUON      ; only while the menu loop runs
        BEQ HVG
        LDX CROW
        CPX #14
        BNE HVL
        LDY CCOL        ; menu row: the word under the pointer
        LDA MENU,Y
        CMP #$20
        BEQ HVG
        CMP #$5F        ; the game separates a prompt label from its choices with this
        BEQ HVG
HM1:    DEY
        BMI HM2
        LDA MENU,Y
        CMP #$20
        BEQ HM2
        CMP #$5F
        BNE HM1
HM2:    INY
        STY HOVD1
        LDY CCOL
HM3:    INY
        CPY #40
        BCS HM4
        LDA MENU,Y
        CMP #$20
        BEQ HM4
        CMP #$5F
        BNE HM3
HM4:    STY HOVD2
        LDY HOVD1       ; lower-case words are prompt/suffix labels, not choices
        LDA MENU,Y
        CMP #'a'
        BCC HM5
        CMP #'z'+1
        BCC HVG
HM5:
        LDA #14
        STA MOLD
HVG:    JMP HVSET
HVL:    CPX #LIST0      ; list row with an item: the row, or the clicked column of two
        BCC HVG
        LDA PROW
        PHA
        LDA PCOL
        PHA
        STX PROW
        LDA CCOL
        STA PCOL
        JSR ITEM
        BEQ HL8
        LDA #0
        STA HOVD1
        LDA #40
        STA HOVD2
        LDY #20
        JSR CHARAT
        CMP #'|'
        BNE HL7
        LDA CCOL
        CMP #20
        BCS HL6
        LDA #20
        STA HOVD2
        BNE HL7
HL6:    LDA #21
        STA HOVD1
HL7:    LDA CROW
        STA MOLD
HL8:    PLA
        STA PCOL
        PLA
        STA PROW
HVSET:  LDA MOLD
        CMP HOVR
        BNE HV1
        CMP #0
        BEQ HV9
        LDA HOVD1
        CMP HOVS
        BNE HV1
        LDA HOVD2
        CMP HOVE
        BEQ HV9
HV1:    JSR HVCLR
        LDX MOLD
        STX HOVR
        BEQ HV9
        LDA HOVD1
        STA HOVS
        LDA HOVD2
        STA HOVE
        JSR ROWADR      ; keep the colour of the first cell
        ADC HOVS
        STA PEEK+1
        TXA
        ADC #$D8
        STA PEEK+2
        JSR PEEK
        STA HOVC
        LDA #COLHOVER
        JMP HVPNT
HV9:    RTS
; Lower-case words are explanatory labels. Repaint them independently of hover so a click cannot
; flash them white; choices such as At-will start with an upper-case shortcut and remain active.
LABELS: LDA MENUON
        BEQ LB9
        LDY #0
LB0:    CPY #40
        BCS LB9
        LDA MENU,Y
        CMP #$20
        BEQ LB1
        CMP #$5F
        BEQ LB1
        CMP #'a'
        BCC LB4
        CMP #'z'+1
        BCS LB4
LB2:    LDA #COLLABEL
        STA $DA30,Y
        INY
        CPY #40
        BCS LB9
        LDA MENU,Y
        CMP #$20
        BEQ LB0
        CMP #$5F
        BNE LB2
        BEQ LB0
LB4:    INY             ; skip an interactive word
        CPY #40
        BCS LB9
        LDA MENU,Y
        CMP #$20
        BEQ LB0
        CMP #$5F
        BNE LB4
LB1:    INY
        BNE LB0
LB9:    RTS
; hover off: the cells get their colour back
HVCLR:  LDX HOVR
        BEQ HV9
        LDA HOVC
        AND #$0F
        JSR HVPNT
        LDA #0
        STA HOVR
        RTS
; A = colour: paints HOVS up to HOVE on row HOVR
HVPNT:  STA TMP3
        LDA $FB
        PHA
        LDA $FC
        PHA
        LDX HOVR
        JSR ROWADR
        STA $FB
        TXA
        ADC #$D8
        STA $FC
        LDA TMP3
        LDY HOVS
HP1:    STA ($FB),Y
        INY
        CPY HOVE
        BNE HP1
        PLA
        STA $FC
        PLA
        STA $FB
        RTS
; Z set if the title is one of the priority lists
RANKABLE: LDA TITLE+1
        LDX #13
        LDY #'-'
        CMP #'E'
        BEQ RK1
        LDX #9
        CMP #'W'
        BEQ RK1
        LDX #8
        CMP #'R'
        BEQ RK1
        LDX #10
        LDY #'D'
        CMP #'S'
        BEQ RK1
        LDA #1          ; Z clear
        RTS
RK1:    TYA
        CMP TITLE,X
        RTS
; A = colour, X = row: paints the row, keeps X. Runs in the IRQ only: too slow for the menu loop,
; where it would delay the raster split.
PAINT:  STA TMP3
        TXA
        PHA
        LDA $FB
        PHA
        LDA $FC
        PHA
        JSR ROWADR
        STA $FB
        TXA
        ADC #$D8
        STA $FC
        LDA TMP3
        LDY #39
PA1:    STA ($FB),Y
        DEY
        BPL PA1
        PLA
        STA $FC
        PLA
        STA $FB
        PLA
        TAX
        RTS
; X = row -> A = its text colour
COLRD:  JSR ROWADR
        ADC #5
        STA PEEK+1
        TXA
        ADC #$D8
        STA PEEK+2
        JSR PEEK
        AND #$0F
        RTS

; ---- text split: sprite 7 becomes the pointer ----
MSPR:   BIT INTXT       ; only with the arrow in its block
        BVC MS9
        LDA INTXT
        ORA #$80
        STA INTXT
        LDA #SHBLOCK    ; the arrow's block; the text screen's pointers are at $53F8
        STA $53FF
        LDA SPX
        STA $D00E
        LDA SPY
        STA $D00F
        LDA $D010
        AND #$7F
        ORA SPM
        STA $D010
        LDA #PTRCOL
        STA $D02E
        LDA #0          ; black outline (the game never uses multicolour)
        STA $D025
        LDA $D01C
        ORA #$80
        STA $D01C
        LDA $D015
        ORA #$80
        STA $D015
MS9:    RTS
; ---- line $82: the arrow goes into its block ----
MXOR:   LDA MOUSEON
        BEQ MS9
        LDA SHSIGA
        CMP #SHSIG
        BNE MS9
        LDA #$40
        STA INTXT
        JMP SHPUT
; ---- top of the screen: sprite 7 back to the game ----
MTOP:   BIT INTXT
        BVC MT1
        JSR SHRST
MT1:    BIT INTXT
        BPL MT8
        LDA SHX
        STA $D00E
        LDA SHY
        STA $D00F
        LDA SHC
        STA $D02E
        LDA $D01C
        AND #$7F
        STA $D01C
        LDA $D010
        AND #$7F
        STA $D010
        LDA GEN
        STA $D015
MT8:    LDA #0
        STA INTXT
        RTS

; ---- joystick read (DDR A = 0): mouse buttons -> click events; returns the joystick byte ----
MJOY:   LDA MENUON
        BEQ MJ0
        DEC MENUON
MJ0:    LDA $DC00
        STA TMP3
        LDX MOUSEON
        BEQ MJ8
        AND #1
        BNE MR0
        LDA RBTN
        BNE MR1
        INC RBTN
        INC RCLICK
MR1:    JMP ML0
MR0:    LDA #0
        STA RBTN
ML0:    LDA TMP3
        AND #$10
        BNE MJREL
        LDA CANCEL
        BNE MJ5
        LDA BTN
        BNE MJ5
        INC BTN         ; press: remember the cell
        LDA HOVR        ; use the menu word visibly highlighted before the press
        CMP #14
        BNE MJPOS
        LDA HOVS
        BPL MJCOL
MJPOS:  LDA CCOL
MJCOL:
        STA PCOL
        LDA CROW
        STA PROW
        BNE MJ5
MJREL:  LDA BTN
        LDA CANCEL
        BEQ MJR0
        LDA #0
        STA CANCEL
MJR0:   LDA BTN
        BEQ MJ5
        LDA #0
        STA BTN
        LDA CROW
        STA RROW
        LDA #1
        STA CLICK
MJ5:    LDA $DC00
        ORA #$11        ; the mouse's own lines are not a joystick
        LDX BTN         ; outside menus a held button is fire
        BEQ MJ8
        LDX MENUON
        BNE MJ8
        AND #$EF
MJ8:    RTS

; ---- menu loop: turn a click into a key or an action ----
MKEY:   LDA #6
        STA MENUON
        LDA RCLICK
        BEQ MK0
        LDA #0
        STA RCLICK
        LDA DRAGR
        BEQ MKBACK
        LDA #1
        STA CANCEL
        RTS
MKBACK: LDA #$14
        JMP PUSHK
MK0:    LSR CLICK
        BCC MKX
        LDX PROW
        CPX #14
        BNE MKL
        LDX PCOL        ; menu row: the word's shortcut key
        LDA MENU,X
        CMP #$20
        BEQ MKX
        CMP #$5F
        BEQ MKX
MK2:    LDA MENU,X      ; back to the start of the word
        CMP #$20
        BEQ MK3
        CMP #$5F
        BEQ MK3
        DEX
        BPL MK2
MK3:    INX
        CPX #40
        BCS MKX
        LDA MENU,X
        CMP #'a'        ; prompt/suffix labels such as priority and robodroids
        BCC MK3A
        CMP #'z'+1
        BCC MKX
MK3A:
        CMP #'?'
        BNE MK4A
        LDA #'/'
MK4A:   CMP #$7F
        BNE MK4
        LDA #$14
MK4:    CMP #$60
        BCC MK5
        AND #$DF        ; lower case -> upper case
MK5:    CMP #'/'
        BCS MK6
        LDA #$14        ; anything below '/' is the back arrow
MK6:    LDX KCOUNT
        STA KQUEUE,X
        INC KCOUNT
MKX:    RTS
MKL:    CPX #LIST0
        BCC MKX
        JSR ITEM
        BEQ MKX         ; no item on this row
        STA ACTARG
        LDX #0          ; the menu's first word
MKM:    LDA MENU,X
        CMP #$20
        BNE MKM1
        INX
        CPX #40
        BNE MKM
        RTS
MKM1:   LDA MENU+1,X
        CMP #$20
        BNE MKIDLE
        LDA MENU,X      ; a one-character word: the game is asking for something
        CMP #'A'
        BCC MKNUM
        LDA ACTARG
        JMP PUSHK
MKNUM:  LDA RROW
        SEC
        SBC #LIST0-'1'
        JMP PUSHK
MKIDLE: LDA MENU,X
        CMP #'P'        ; "Processing_Command"
        BEQ MKX3
        LDA TITLE+1
        CMP #'E'
        BEQ MKENG
        CMP #'N'
        BEQ MKNAV
        CMP #'W'
        BEQ MKWEAP
        CMP #'R'
        BEQ MKREP
        CMP #'S'
        BNE MKX3
        LDA TITLE+10    ; SCANNING DETAILED EXAMINATION LIST
        CMP #'D'
        BNE MKSCAN
        LDA #'S'
        LDX #2
        BNE DRAG
MKSCAN: JSR SAMEROW     ; SCANNING STATUS REPORT: examine
        BNE MKX3
        JSR SAVE
        LDA #'1'
        STA $30
        LDA #'S'
        STA $38
        LDA #2
        STA $39
        LDA #3
        STA ACT
        RTS
MKX3:   RTS
MKREP:  LDA TITLE+8     ; REPAIR -- FIX-IT LIST
        CMP #'-'
        BNE MKREP1
        LDA #'R'
        LDX #3
        BNE DRAG
MKREP1: JSR SAMEROW     ; REPAIR STATUS: Assign, the game then asks how many robodroids
        BNE MKX3
        LDA #'A'
        JSR PUSHK
        LDA ACTARG
        JMP PUSHK
MKWEAP: LDA TITLE+9     ; WEAPONS - FIRING ORDERS LIST
        CMP #'-'
        BNE MKX3
        LDA #'W'
        LDX #1
        BNE DRAG
MKNAV:  JSR SAMEROW     ; a course on either Navigation list: select it
        BNE MKX3
        LDA #'N'
        LDX #0
        LDY #'1'
        JMP RANK
MKENG:  LDA TITLE+13
        CMP #'S'
        BNE MKENG1
        JMP MKSTAT
MKENG1: CMP #'-'
        BNE MKX3
        LDA #'E'
        LDX #4
DRAG:   TAY             ; drag to another list row = rank there
        LDA RROW
        CMP PROW
        BEQ MKX2
        CMP #LIST0
        BCC MKX2
        SEC
        SBC #LIST0-'1'
        STA TMP2
        TYA
        LDY TMP2
RANK:   PHA             ; A = department letter, X = its index, Y = position
        TXA
        PHA
        TYA
        PHA
        JSR SAVE
        PLA
        STA $30
        PLA
        STA $39
        PLA
        STA $38
        LDA $30         ; flash the rows that change
        SEC
        SBC #'1'-LIST0
        STA FLTGT
        LDA PROW
        PHA
RN1:    LDA FLTGT       ; past the end of the list: the last item's row
        STA PROW
        JSR ITEM
        BNE RN2
        DEC FLTGT
        LDA FLTGT
        CMP #LIST0
        BCS RN1
        INC FLTGT
RN2:    PLA
        STA PROW
        LDA DRAGR       ; (otherwise BASEC is still valid)
        BNE RN3
        LDX PROW
        JSR COLRD
        STA BASEC
RN3:    LDA PROW
        LDX FLTGT
        CMP FLTGT
        BCC RN4
        STX FLLO
        STA FLHI
        BCS RN5
RN4:    STA FLLO
        STX FLHI
RN5:    LDA #$FF
        STA FLT
        LDA #2
        STA ACT
MKX2:   RTS
MKSTAT: JSR SAMEROW     ; ENGINEERING STATUS REPORT: click a device = toggle it
        BNE MKX2
        LDA ACTARG
        CMP #'M'
        BCS MKX2
        SEC
        SBC #'A'
        TAX
        LDA DEVSTATE,X
        ASL A
        LDA #0
        ROL A
        EOR #1          ; enabled -> 0 (cancel), off -> 1 (enable)
        STA ACTA
        JSR SAVE
        LDA #1
        STA ACT
        RTS

; Z set if the button was released on the row it was pressed on
SAMEROW: LDA RROW
        CMP PROW
        RTS
; keep the command record of a half-typed command, $2F = the clicked item
SAVE:   LDY #13
SV1:    LDA $2D,Y
        STA RECBUF,Y
        DEY
        BPL SV1
        LDA ACTARG
        STA $2F
        RTS
PUSHK:  LDX KCOUNT
        STA KQUEUE,X
        INC KCOUNT
        RTS
; A = the item letter on row PROW in the clicked column, 0 if none (Z set accordingly):
; the first thing in the column, a capital followed by a blank
ITEM:   LDY #0
        LDA PCOL
        CMP #20
        BCC IT1
        LDY #20         ; two columns?
        JSR CHARAT
        LDY #0
        CMP #'|'
        BNE IT1
        LDY #22
IT1:    STY TMP2
        LDA #5
        STA TMP3
IT2:    LDY TMP2
        JSR CHARAT
        CMP #$20
        BNE IT3
        INC TMP2
        DEC TMP3
        BNE IT2
        BEQ IT8
IT3:    CMP #'A'
        BCC IT8
        CMP #'Z'+1
        BCS IT8
        STA TMP3
        LDY TMP2
        INY
        JSR CHARAT
        CMP #$20
        BNE IT8
        LDA TMP3
        RTS
IT8:    LDA #0
        RTS

; A = character at row PROW, column Y of the text screen
CHARAT: STY TMP
        LDX PROW
        JSR ROWADR
        CLC
        ADC TMP
        STA PEEK+1
        TXA
        ADC #$50
        STA PEEK+2
        JMP PEEK

; X = row -> A = low byte, X = high byte of row*40 (carry clear). Uses RCA as scratch.
ROWADR: LDA #0
        STA RCA
        TXA
        ASL A
        ASL A
        ASL A           ; *8 (rows < 32)
        STA MNEW
        ASL A
        ROL RCA
        ASL A
        ROL RCA         ; *32
        CLC
        ADC MNEW        ; *40
        BCC RA1
        INC RCA
        CLC
RA1:    LDX RCA
        RTS

; CBM MOVCHK: A = new pot, Y = old -> A = signed delta, Y = value to keep
MOVCHK: STY MOLD
        STA MNEW
        SEC
        SBC MOLD
        AND #$7F
        CMP #$40
        BCC MV1
        ORA #$C0
        CMP #$FF        ; -1 is jitter
        BNE MV0
        LDA #0
        RTS
MV0:    SEC
        ROR A
        BNE MVOK
