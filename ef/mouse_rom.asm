; CBM MOVCHK: A = new pot, Y = old -> A = signed delta, Y = value to keep
MOVCHK: STY MOLD
        STA MNEW
        SEC
        SBC MOLD
        AND #$7F
        CMP #$40
        BCC MV1
        ORA #$C0
        CMP #$FF        ; -1 is jitter
        BNE MV0
        LDA #0
        RTS
