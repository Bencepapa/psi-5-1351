; Psi-5 EasyFlash: mouse support, ROM part (own bank, ROML at $8000, called via mouse_ram.asm).
; Bridge code touches I/O, RAM below $8000 and the RAM part's variables.
; The front-end extension also stores its course pointer in RAM under KERNAL.
; Pointer: sprite 7 in the text rows, multiplexed by the RAM part (the ships use it above the
; split). Mouse in port 2.
; - menu-row hover sets the native cursor and command ordinal directly; click fires that choice
; - while the game asks for an item or a position: click a list row = that letter or row number
; - otherwise, on the list screens:
;   Engineering status: click a device = enable/cancel it ($95AC)
;   Navigation, status or course list: click a course = select it (rank 1, $8AE7)
;   Scanning status: click a target = examine it ($8CFC)
;   Repair status: click a damaged item = types Assign + its letter, the game asks how many
;   Priority lists (Engineering, Weapons, Repair, Scanning): drag a row to another row = rank ($8AE7)
; - outside menus a click is the fire button
KQUEUE   = $03CA
KCOUNT   = $4E
DEVSTATE = $58CC
TITLE    = $5000+15*40
MENU     = $5000+14*40
LIST0    = 17            ; first list row
DRAGR    = $DFFA         ; greyed row while dragging, 0 = none (end of the cartridge's RAM)
BASEC    = $DFFB         ; the list rows' colour
FLT      = $DFFC         ; flash: frames left, $FF = start; $80|row paint, $C0|row restore
FLLO     = $DFFD         ; rows FLLO-FLHI changed, FLTGT is the moved one
FLHI     = $DFFE
FLTGT    = $DFFF
COLGREY  = 12
COLHOVER = 1              ; white
COLLABEL = 3              ; cyan, for non-interactive prompt/suffix text
HOVC     = $DBE8          ; saved hover colour, or Navigation's last hovered row offset
NAVON    = $DBE9          ; bit 0: Nav colour ownership; bit 1: last first row was yellow
HOVD1    = $53F6          ; unused end of the text screen: scratch
HOVD2    = $53F7
COLMOVED = 7             ; yellow
COLSHIFT = 6             ; blue
FLASHLEN = 40            ; frames
; The arrow's sprite block: $6080 (block $82), a piece of the frame's art in the top row of the
; bitmap. Nothing in the VIC bank is free, so this block shows the arrow from line $82 down and
; gets its art back at line $2D. SHPUT and SHRST are generated by efbuild.py, which reads the art
; and the shape below (unrolled LDA #/STA abs: 6 cycles a byte). SHSIGA/SHSIG: an art byte that
; says the game's bitmap is loaded.

        * = $8000
        JMP MPRE        ; fixed entry points for the RAM part
        JMP MJOY
        JMP MKEY
        JMP MSPR
        JMP MTOP
        JMP MXOR
        JMP MREST
; ---- IRQ: pots, pointer ----
MPRE:   LDA $D419
        AND $D41A
        EOR #$FF        ; $FF on both pots = no 1351 in port 2
        STA MOUSEON
        BNE MP0
        RTS
MP0:    LDA $D419
        LDY OLDX
        JSR MOVCHK
        STY OLDX
        CMP #$80        ; /2 keeping the sign: x in 2-pixel units 0-159
        ROR A
        CLC
        ADC XP
        CMP #160
        BCC MP2
        CMP #$C8        ; past the right edge (160-199) or the left edge (wrapped)
        LDA #159
        BCC MP2
        LDA #0
MP2:    STA XP
        LSR A
        LSR A
        STA CCOL
        LDA $D41A
        LDY OLDY
        JSR MOVCHK
        STY OLDY
        EOR #$FF        ; pot Y grows upwards
        SEC
        ADC YP
        CMP #110        ; not above the split (the sprite is set at raster $9A-$9E)
        BCS MP5
        LDA #110
MP5:    CMP #200
        BCC MP6
        LDA #199
MP6:    STA YP
        TAX
        LSR A
        LSR A
        LSR A
        STA CROW
        TXA
        CLC
        ADC #50
        STA SPY
        LDA #0          ; sprite X = 2*XP+24
        STA SPM
        LDA XP
        ASL A
        ROR SPM
        ADC #24
        STA SPX
        BCC MP7
        LDA #$80
        STA SPM
MP7:
MP9:    LDA INTXT
        ORA #1          ; visual update pending for the main menu loop
        STA INTXT
        LDA CROW
        CMP #14
        BNE MPDONE
        LDA HOVR
        CMP #LIST0
        BCS MPDONE      ; removing an old list overlay belongs to the main-loop update
        JMP HOVER       ; native menu targeting; no list scan or row paint
MPDONE:
        RTS
; ---- list colours: the dragged row grey, then a flash of the rows that changed ----
VIS:    JSR LABELS      ; safety net outside the raster-critical input path
        JSR REPLAYTITLE
        LDA TITLE+1
        CMP #'N'
        BNE VOTHER
        LDA TITLE+12
        CMP #'-'
        BNE VOTHER
        JMP NAVVIS
VOTHER: LDA NAVON
        AND #1
        BEQ VNORMAL
        JSR NAVCLEAR    ; never carry Navigation's hover/flash into another division
VNORMAL:
        LDA CANCEL
        BEQ VGO
        JMP VCANCEL
VGO:    LDA BTN
        BNE VHOLD
        JMP VREL
VHOLD:  JSR HVCLR
        LDA DRAGR
        BNE VPRE
        LDX PROW
        CPX #LIST0
        BCS VV0
        JMP VFL
VV0:
        JSR RANKABLE
        BEQ VRANK
        JMP VFL
VRANK:
        JSR ITEM
        BNE VITEM
        JMP VFL
VITEM:
        LDX PROW
        STX DRAGR
        LDA FLT
        BNE VBASE       ; existing flash colours are temporary, keep the original base
        JSR COLRD
        STA BASEC
VBASE:
        LDA #COLGREY
        LDX PROW
        JSR PAINT
; the row under the pointer previews the new position (the last item's row past the list's end).
; ITEM uses TMP2/TMP3, ROWADR uses MNEW; MOLD is free here (MOVCHK has finished).
VPRE:   LDA #0
        STA MOLD
        LDX CROW
        CPX #LIST0
        BCC VP3
        STX MOLD
        LDA PROW
        PHA
VP1:    LDA MOLD
        STA PROW
        JSR ITEM
        BNE VP2
        DEC MOLD
        LDA MOLD
        CMP #LIST0
        BCS VP1
        LDA #0
        STA MOLD
VP2:    PLA
        STA PROW
VP3:    LDA MOLD
        CMP DRAGR
        BNE VP4
        LDA #0
        STA MOLD
VP4:    LDA MOLD
        CMP PREVW
        BEQ VP9         ; repaint only on a change
        LDX PREVW
        BEQ VP5
        LDA BASEC
        JSR PAINT
VP5:    LDX MOLD
        STX PREVW
        BEQ VP9
        LDA #COLMOVED
        JSR PAINT
VP9:    JMP VFL
VREL:   LDX DRAGR
        BEQ VFL
        LDX PREVW
        BEQ VR1
        LDA BASEC
        JSR PAINT
        LDA #0
        STA PREVW
VR1:    LDX DRAGR
        LDA BASEC
        JSR PAINT
        LDA #0
        STA DRAGR
        RTS
VCANCEL:LDA #0
        STA BTN
        JMP VREL
VFL:    LDA FLT
        BNE VFL1
        JMP HOVER
VFL1:
        CMP #$FF
        BEQ VFSTART
        CMP #$C0
        BCS VFREST
        CMP #$80
        BCC VF3
        AND #$1F
        TAX
        JMP VF1
VFSTART:
        LDX FLLO
VF1:    LDA #COLSHIFT
        CPX FLTGT
        BNE VF2
        LDA #COLMOVED
VF2:    JSR PAINT
        INX
        CPX FLHI
        BCC VFNEXT
        BEQ VFNEXT
        LDA #FLASHLEN
        STA FLT
VX:     RTS
VFNEXT: TXA
        ORA #$80
        STA FLT
        RTS
VF3:    DEC FLT
        BNE VX
        LDX FLLO
        JMP VF4
VFREST: AND #$1F
        TAX
VF4:    LDA BASEC
        JSR PAINT
        INX
        CPX FLHI
        BCC VFRNEXT
        BEQ VFRNEXT
        LDA #0
        STA FLT
        RTS
VFRNEXT:TXA
        ORA #$C0
        STA FLT
        RTS
; ---- hover: list actions use a mouse preview; menu-row hover drives the native cursor ----
; HOVR/HOVS/HOVE: list overlay row and bounds, or menu marker/word start/unused zero. HOVD1/HOVD2
; hold the current word's screen columns. The menu's native cursor endpoint is at $0774.
HOVER:  LDA BTN
        ORA DRAGR
        BEQ HV0
        RTS
HV0:
        STA MOLD
        LDA MENUON      ; only while the menu loop runs
        BNE HVACTIVE
        JMP HVG
HVACTIVE:
        LDX CROW
        CPX #14
        BEQ HVMENU
        JMP HVL
HVMENU:
        LDY CCOL        ; menu row: the word under the pointer
        LDA MENU,Y
        CMP #$20
        BNE HM1
        JMP HVG
HM1:    DEY
        BMI HM2
        LDA MENU,Y
        CMP #$20
        BEQ HM2
        BNE HM1
HM2:    INY
        STY HOVD1
        LDY CCOL
HM3:    INY
        CPY #40
        BCS HM4
        LDA MENU,Y
        CMP #$20
        BEQ HM4
        BNE HM3
HM4:    STY HOVD2
        LDY HOVD1       ; lower-case words are prompt/suffix labels, not choices
        LDA MENU,Y
        CMP #'a'
        BCC HM5
        CMP #'z'+1
        BCS HM5
        ; An underscore is part of a native choice (Same_crew_&_course).
        ; Only a lowercase prompt prefix before '_' is non-interactive.
HMPREFIX:INY
        CPY HOVD2
        BCS HVG
        LDA MENU,Y
        CMP #$5F
        BNE HMPREFIX
        INY
        STY HOVD1
        CPY CCOL
        BCC HM5
        BEQ HM5
        BCS HVG
HM5:
        LDA HOVR
        CMP #14
        BEQ HM6
        JSR HVCLR       ; leave any list-row overlay before switching to native menu selection
        LDA #0
        STA HOVE
        BEQ HM7
HM6:    LDA HOVS
        CMP HOVD1
        BEQ HM7
        LDA #0
        STA HOVE        ; menu targets do not use list end-column bounds
HM7:    LDA #14
        STA HOVR        ; mark a native menu target; do not paint a second highlight
        LDA HOVD1
        STA HOVS
        RTS
HVG:    JMP HVSET
HVL:    CPX #LIST0      ; list row with an item: the row, or the clicked column of two
        BCC HVG
        LDA PROW
        PHA
        LDA PCOL
        PHA
        STX PROW
        LDA CCOL
        STA PCOL
        JSR ITEM
        BEQ HL8
        LDA #0
        STA HOVD1
        LDA #40
        STA HOVD2
        LDY #20
        JSR CHARAT
        CMP #'|'
        BNE HL7
        LDA CCOL
        CMP #20
        BCS HL6
        LDA #20
        STA HOVD2
        BNE HL7
HL6:    LDA #21
        STA HOVD1
HL7:    LDA CROW
        STA MOLD
HL8:    PLA
        STA PCOL
        PLA
        STA PROW
HVSET:  LDA MOLD
        CMP HOVR
        BNE HV1
        CMP #0
        BEQ HV9
        LDA HOVD1
        CMP HOVS
        BNE HV1
        LDA HOVD2
        CMP HOVE
        BEQ HV9
HV1:    JSR HVCLR
        LDX MOLD
        STX HOVR
        BEQ HV9
        LDA HOVD1
        STA HOVS
        LDA HOVD2
        STA HOVE
        JSR ROWADR      ; keep the colour of the first cell
        ADC HOVS
        STA PEEK+1
        TXA
        ADC #$D8
        STA PEEK+2
        JSR PEEK
        STA HOVC
        LDA #COLHOVER
        JMP HVPNT
HV9:    RTS
; Lower-case words are explanatory labels. Repaint them independently of hover so a click cannot
; flash them white; choices such as At-will start with an upper-case shortcut and remain active.
LABELS: LDA MENUON
        BEQ LB9
        LDY #0
LB0:    CPY #40
        BCS LB9
        LDA MENU,Y
        CMP #$20
        BEQ LB1
        CMP #$5F
        BEQ LB1
        CMP #'a'
        BCC LB4
        CMP #'z'+1
        BCS LB4
LB2:    LDA #COLLABEL
        STA $DA30,Y
        INY
        CPY #40
        BCS LB9
        LDA MENU,Y
        CMP #$20
        BEQ LB0
        CMP #$5F
        BNE LB2
        BEQ LB0
LB4:    INY             ; skip an interactive word
        CPY #40
        BCS LB9
        LDA MENU,Y
        CMP #$20
        BEQ LB0
        BNE LB4        ; underscores inside an uppercase choice are not label separators
LB1:    LDA MENU,Y
        CMP #$5F
        BNE LB1A
        LDA #COLLABEL
        STA $DA30,Y     ; keep the prompt/choice separator cyan, not in the white cursor
LB1A:   INY
        BNE LB0
LB9:    RTS
; hover off: the cells get their colour back
HVCLR:  LDX HOVR
        BEQ HV9
        CPX #14
        BEQ HVCLEAR
        LDA HOVC
        AND #$0F
        JSR HVPNT
HVCLEAR:
        LDA #0
        STA HOVR
        RTS
; A = colour: paints HOVS up to HOVE on row HOVR
HVPNT:  STA TMP3
        LDA $FB
        PHA
        LDA $FC
        PHA
        LDX HOVR
        JSR ROWADR
        STA $FB
        TXA
        ADC #$D8
        STA $FC
        LDA TMP3
        LDY HOVS
HP1:    STA ($FB),Y
        INY
        CPY HOVE
        BNE HP1
        PLA
        STA $FC
        PLA
        STA $FB
        RTS
; Z set if the title is one of the priority lists
RANKABLE: LDA TITLE+1
        LDX #13
        LDY #'-'
        CMP #'E'
        BEQ RK1
        LDX #9
        CMP #'W'
        BEQ RK1
        LDX #8
        CMP #'R'
        BEQ RK1
        LDX #10
        LDY #'D'
        CMP #'S'
        BEQ RK1
        LDA #1          ; Navigation selects a course; it has no drag ranking
        RTS
RK1:    TYA
        CMP TITLE,X
        RTS
; A = colour, X = row: paints the row, keeps X. Visual updates run in the
; main loop's lower-screen window; never paint list rows from the split IRQ.
PAINT:  STA TMP3
        TXA
        PHA
        LDA $FB
        PHA
        LDA $FC
        PHA
        JSR ROWADR
        STA $FB
        TXA
        ADC #$D8
        STA $FC
        LDA TMP3
        LDY #39
PA1:    STA ($FB),Y
        DEY
        BPL PA1
        PLA
        STA $FC
        PLA
        STA $FB
        PLA
        TAX
        RTS
; X = row -> A = its text colour
COLRD:  JSR ROWADR
        ADC #5
        STA PEEK+1
        TXA
        ADC #$D8
        STA PEEK+2
        JSR PEEK
        AND #$0F
        RTS

; ---- text split: sprite 7 becomes the pointer ----
MSPR:   BIT INTXT       ; only with the arrow in its block
        BVC MS9
        LDA INTXT
        ORA #$80
        STA INTXT
        LDA #SHBLOCK    ; the arrow's block; the text screen's pointers are at $53F8
        STA $53FF
        LDA SPX
        STA $D00E
        LDA SPY
        STA $D00F
        LDA $D010
        AND #$7F
        ORA SPM
        STA $D010
        LDA #PTRCOL
        STA $D02E
        LDA #0          ; black outline (the game never uses multicolour)
        STA $D025
        LDA $D01C
        ORA #$80
        STA $D01C
        LDA $D015
        ORA #$80
        STA $D015
MS9:    RTS
; ---- line $82: the arrow goes into its block ----
MXOR:   LDA MOUSEON
        BEQ MS9
        LDA SHSIGA
        CMP #SHSIG
        BNE MS9
        LDA #$40
        STA INTXT
        JMP SHPUT
; ---- top of the screen: sprite 7 back to the game ----
MTOP:   BIT INTXT
        BVC MT1
        JSR SHRST
MT1:    BIT INTXT
        BPL MT8
        LDA SHX
        STA $D00E
        LDA SHY
        STA $D00F
        LDA SHC
        STA $D02E
        LDA $D01C
        AND #$7F
        STA $D01C
        LDA $D010
        AND #$7F
        STA $D010
        LDA GEN
        STA $D015
MT8:    LDA #0
        STA INTXT
        RTS

; ---- joystick read (DDR A = 0): mouse buttons -> click events; returns the joystick byte ----
MJOY:   LDA $0315
        CMP #$1E
        BNE MJBRIDGE
        LDA $0314
        CMP #$EB
        BNE MJBRIDGE
        JMP FJOY
MJBRIDGE:LDA MENUON
        BEQ MJ0
        DEC MENUON
MJ0:    LDA $DC00
        STA TMP3
        LDX MOUSEON
        BNE MJHAS
        LDA TMP3
        RTS
MJHAS:  AND #1
        BNE MR0
        LDA RBTN
        BNE MR1
        INC RBTN
        INC RCLICK
MR1:    JMP ML0
MR0:    LDA #0
        STA RBTN
ML0:    LDA TMP3
        AND #$10
        BNE MJREL
        LDA CANCEL
        BNE MJ5
        LDA BTN
        BNE MJ5
        INC BTN         ; press: remember the cell
        LDA HOVR
        CMP #14
        BNE MJPOS
        LDA CROW
        CMP #14
        BNE MJPOS
        LDA HOVD2       ; PCOL stores the native cursor position for deferred activation
        SEC
        SBC #2
        BPL MJCOL
MJPOS:  LDA CROW
        CMP #14
        BNE MJPC
        LDA #$FF        ; row-14 text that is not a native menu choice
        BNE MJCOL
MJPC:   LDA CCOL
MJCOL:
        STA PCOL
        LDA CROW
        STA PROW
        BNE MJ5
MJREL:  LDA CANCEL
        BEQ MJR0
        LDA #0
        STA CANCEL
        STA BTN         ; cancelled/already-fired presses must not become a second click
        JMP MJ5
MJR0:   LDA BTN
        BEQ MJ5
        LDA #0
        STA BTN
        LDA CROW
        STA RROW
        LDA #1
        STA CLICK
MJ5:    LDA MENUON
        BEQ MJN0
        LDA CLICK
        BEQ MJNH
        LDA PROW
        CMP #14
        BNE MJNH
        LDA PCOL
        CMP #$FF
        BEQ MJN0
        STA TMP2
        JMP MJTE
MJNH:   LDA HOVR
        CMP #14
        BNE MJN0
        LDA HOVD2       ; $0774 stores the last choice character relative to column 1
        SEC
        SBC #2
        STA TMP2
MJTE:
        LDA TMP3
        AND #$0C
        CMP #$0C        ; physical joystick direction takes precedence
        BNE MJN0
        JSR SELECT      ; update the native cursor and command ordinal atomically
MJN0:   LDA HOVR
        CMP #14
        BNE MJN1        ; HOVE is the list's end column outside native menu targeting
        LDA #0
        STA HOVE
MJN1:   LDA $DC00
        ORA #$11        ; the mouse's own lines are not a joystick
        LDX BTN         ; outside menus a held button is fire
        BEQ MJNPEND
        LDX MENUON
        BEQ MJFIRE
        LDA PROW
        CMP #14
        BNE MJNOFIRE
        LDA HOVR
        CMP #14
        BNE MJNOFIRE
        LDA TMP2
        CMP $0774       ; fire only after the native highlight reaches the pointer
        BNE MJNOFIRE
        LDA #1
        STA CANCEL      ; remember that the held menu click already fired
MJFIRE: LDA $DC00
        ORA #$11
        AND #$EF
        JMP MJN2
MJNPEND:
        LDA CLICK
        BEQ MJNOFIRE
        LDA PROW
        CMP #14
        BNE MJNOFIRE
        LDA PCOL
        CMP #$FF
        BEQ MJNOFIRE
        LDA TMP2
        CMP $0774
        BNE MJNOFIRE
        LDA #0
        STA CLICK
        JMP MJFIRE
MJNOFIRE:
        LDA $DC00
        ORA #$11
MJN2:
MJ8:    RTS

; TMP2 = native word endpoint (screen column minus 1). Space-separated words
; are the game's actual choices; '_' belongs to the priority_1 native word.
SELECT: LDA TMP2
        CMP $0774
        BEQ SEL9
        CMP #39
        BCS SEL9
        LDY #0
        LDX #0
SEL0:   LDA $5231,Y
        CMP #$20
        BEQ SELSPACE
        INX
        STY MNEW
SELWORD:CPY TMP2
        BEQ SELFOUND
        INY
        LDA $5231,Y
        CMP #$20
        BNE SELWORD
SELSPACE:INY
        CPY #39
        BCC SEL0
SEL9:   RTS
SELFOUND:
        STX $3D         ; ordinal used by the native fire handler at $86C0
        STY $0774
        LDA MNEW
        STA $4D
        LDX $37         ; native cursor moves invalidate deeper remembered choices
        INX
        LDA #0
SELCACHE:STA $0421,X
        INX
        CPX #10
        BNE SELCACHE
        LDY #39
        LDA #COLLABEL
SELCYAN:STA $DA30,Y
        DEY
        BPL SELCYAN
        LDY $4D
SELWHITE:JSR WPMENU
        CPY TMP2
        BEQ SEL9
        INY
        BNE SELWHITE

; Restore the command record after a native action, with the mouse bank mapped.
MREST:  LDY #13
MRS1:   LDA RECBUF,Y
        STA $2D,Y
        DEY
        BPL MRS1
        LDA #0
        STA ACT
        RTS

; ---- menu loop: turn a click into a key or an action ----
; ROMCALL masks interrupts while ROML is mapped. Run the visual work once per
; frame, starting on PAL lines 240-295, before the $2D top split next frame.
; INTXT bit 0 is pending; bits 6/7 retain their sprite meanings.
MKEY:   LDA INTXT
        AND #1
        BEQ MKVIS9
        LDA $D011
        BMI MKVHIGH
        LDA $D012
        CMP #240
        BCC MKVIS9
        BCS MKVRUN
MKVHIGH:LDA $D012
        CMP #40
        BCS MKVIS9
        LDA $D011       ; reject a frame wrap between the two raster reads
        BPL MKVIS9
MKVRUN:
        LDA INTXT
        AND #$FE
        STA INTXT
        JSR VIS
MKVIS9: LDA #6
        STA MENUON
        LDA RCLICK
        BEQ MK0
        LDA #0
        STA RCLICK
        LDA DRAGR
        BEQ MKBACK
        LDA #1
        STA CANCEL
        RTS
MKBACK: LDA #$14
        JMP PUSHK
MK0:    LDA CLICK
        BEQ MKX
        LDX PROW
        CPX #14
        BNE MKL
        LDA PCOL
        CMP #$FF
        BEQ MKDROP
        RTS             ; native menu click stays pending until MJOY fires the selected item
MKDROP: LDA #0
        STA CLICK
        RTS
        LDX PCOL        ; menu row: the word's shortcut key
        LDA MENU,X
        CMP #$20
        BEQ MKX
        CMP #$5F
        BEQ MKX
MK2:    LDA MENU,X      ; back to the start of the word
        CMP #$20
        BEQ MK3
        CMP #$5F
        BEQ MK3
        DEX
        BPL MK2
MK3:    INX
        CPX #40
        BCS MKX
        LDA MENU,X
        CMP #'a'        ; prompt/suffix labels such as priority and robodroids
        BCC MK3A
        CMP #'z'+1
        BCC MKX
MK3A:
        CMP #'?'
        BNE MK4A
        LDA #'/'
MK4A:   CMP #$7F
        BNE MK4
        LDA #$14
MK4:    CMP #$60
        BCC MK5
        AND #$DF        ; lower case -> upper case
MK5:    CMP #'/'
        BCS MK6
